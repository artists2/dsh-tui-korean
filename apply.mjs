import { readFileSync, writeFileSync, copyFileSync, existsSync, mkdirSync, rmSync, readdirSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';

const HERE = dirname(fileURLToPath(import.meta.url));

// Locate the installed dsh-TUI package:
//   1. `--pkg <path>` argument
//   2. DSH_TUI_PKG environment variable
//   3. ~/.dsh/profiles/<profile>/node_modules/@deepseek-harness-tui/dsh-tui
const flag = (name) => {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
};
const profile = flag('--profile') ?? 'dsh-tui';
const PKG =
  flag('--pkg') ??
  process.env.DSH_TUI_PKG ??
  join(homedir(), '.dsh', 'profiles', profile, 'node_modules', '@deepseek-harness-tui', 'dsh-tui');

if (!existsSync(join(PKG, 'package.json'))) {
  console.error(`dsh-TUI package not found: ${PKG}`);
  console.error('Pass --pkg <path> or set DSH_TUI_PKG.');
  process.exit(1);
}
const TYPES = join(PKG, 'lib', 'types');

// A TUI update replaces lib/types. The pristine backups from the previous
// version must not be reused, or the old files would be written back.
const pkgVersion = JSON.parse(readFileSync(PKG + '/package.json', 'utf8')).version;
const stamp = join(HERE, '.applied-version');
const recorded = existsSync(stamp) ? readFileSync(stamp, 'utf8').trim() : '';
if (recorded && recorded !== pkgVersion) {
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith('.ko-orig')) rmSync(p);
    }
  };
  walk(TYPES);
  console.log(`package version ${recorded} -> ${pkgVersion}: dropped stale backups`);
}

const base = JSON.parse(readFileSync(join(HERE, 'ko.json'), 'utf8'));

// Keys that only exist after adding a Korean language, plus copy that must
// name the new language code.
